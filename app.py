# ==============================
# ข้อมูลภาษาไทย
# ==============================

THAI_MONTHS = [
    "มกราคม",
    "กุมภาพันธ์",
    "มีนาคม",
    "เมษายน",
    "พฤษภาคม",
    "มิถุนายน",
    "กรกฎาคม",
    "สิงหาคม",
    "กันยายน",
    "ตุลาคม",
    "พฤศจิกายน",
    "ธันวาคม",
]

THAI_DAYS = [
    "จันทร์",
    "อังคาร",
    "พุธ",
    "พฤหัสบดี",
    "ศุกร์",
    "เสาร์",
    "อาทิตย์",
]


# ==============================
# ฟังก์ชันแปลงวันที่
# ==============================

def thai_date_text(dt):
    month = THAI_MONTHS[dt.month - 1]
    year = dt.year + 543

    return f"{dt.day} {month} {year}"


# ==============================
# เวลาไทย
# ==============================

bangkok = ZoneInfo("Asia/Bangkok")
now = datetime.now(bangkok)


